import { Request, Response } from "express";
import { getPool, sql } from "../../../config/db";
import { responder } from "../../../responses/codes";
import { CarritoModel } from "../../../models/PROD/CARRITO/carritoModel";


export const store = async (req: Request, res: Response): Promise<void> => {
  const body = (req.body ?? {}) as CarritoModel;
  const IDUsuario = body.IDUsuario;
  const usuario = body.usuario;

  if (!IDUsuario) {
    responder(res, 1004, undefined, "El usuario del carrito es obligatorio");
    return;
  }

  let pool;

  try {
    pool = await getPool();
  } catch (error) {
    console.error(error);
    responder(res, 1001);
    return;
  }

  try {
    const result = await pool
      .request()
      .input("opcion", sql.Int, 1)
      .input("IDUsuario", sql.Int, IDUsuario)
      .input("usuario", sql.VarChar(50), usuario)
      .execute("SP_Modulo_Carrito");

    responder(res, 1, result.recordset);
  } catch (error) {
    console.error(error);
    responder(res, 1002);
  }
};


